// Copies the chapter map art and game-screen backgrounds from design/maps/
// into public/maps/, and writes src/game/chapters.ts from the node files.
// Re-run after the design changes:  node scripts/import-chapter-maps.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync } from 'node:fs';

const SRC = 'design/maps/';
const OUT = 'public/maps/';
mkdirSync(OUT, { recursive: true });

// Names and locked-tile colours, as in design/maps/build-chapters.mjs.
const CHAPTERS = [
  [1, 'kiln-meadow', 'Kiln Meadow'],
  [2, 'clay-creek', 'Clay Creek'],
  [3, 'sunflower-fields', 'Sunflower Fields'],
  [4, 'market-town', 'Market Town'],
  [5, 'seaside-pier', 'Seaside Pier'],
  [6, 'bluegum-forest', 'Bluegum Forest'],
  [7, 'lantern-gardens', 'Lantern Gardens'],
  [8, 'snowy-peaks', 'Snowy Peaks'],
  [9, 'glass-desert', 'Glass Desert'],
  [10, 'great-kiln', 'The Great Kiln'],
];
const LOCKED = { 8: ['#cdbfae', '#8f7a58'] };
const DEFAULT_LOCKED = ['#d9c7a8', '#a8926e'];

const files = readdirSync(SRC);
const entries = CHAPTERS.map(([n, id, name]) => {
  const art = `chapter-${n}-${id}.svg`;
  const bg = `chapter-${n}-background.svg`;
  if (!files.includes(art) || !files.includes(bg)) throw new Error(`Missing art for chapter ${n}`);
  copyFileSync(SRC + art, `${OUT}chapter-${n}-map.svg`);
  copyFileSync(SRC + bg, `${OUT}chapter-${n}-background.svg`);

  const json = JSON.parse(readFileSync(`${SRC}chapter-${n}-nodes.json`, 'utf8'));
  if (json.levels.length !== 20) throw new Error(`Chapter ${n} has ${json.levels.length} nodes, not 20`);
  json.levels.forEach((l, i) => {
    if (l.level !== (n - 1) * 20 + i + 1) throw new Error(`Chapter ${n} node ${i} is level ${l.level}`);
  });
  const nodes = json.levels.map((l) => `[${l.x}, ${l.y}]`).join(', ');
  const locked = LOCKED[n] ?? DEFAULT_LOCKED;
  return `  {\n    n: ${n},\n    slug: '${id}',\n    name: '${name.replace(/'/g, "\\'")}',\n    width: ${json.width},\n    height: ${json.height},\n    locked: ['${locked[0]}', '${locked[1]}'],\n    nodes: [${nodes}],\n  },`;
});

writeFileSync(
  'src/game/chapters.ts',
  `/**
 * The ten chapters of the level select: one illustrated map per 20 levels.
 * Generated by scripts/import-chapter-maps.mjs from design/maps/; do not
 * edit by hand. The art lives in public/maps/ as chapter-N-map.svg (the
 * road, ${'375'} wide) and chapter-N-background.svg (the game screen).
 */

export interface Chapter {
  n: number;
  /** File-name form of the name, as the design files use it (pots, maps). */
  slug: string;
  name: string;
  /** Size of the map art, in the units the node positions use. */
  width: number;
  height: number;
  /** Face and edge colour of a locked level tile on this map. */
  locked: [string, string];
  /** Centre of each level's tile, in order, first level first. */
  nodes: [number, number][];
}

export const CHAPTER_SIZE = 20;

export const CHAPTERS: Chapter[] = [
${entries.join('\n')}
];

export function chapterOf(levelId: number): Chapter {
  const index = Math.min(CHAPTERS.length - 1, Math.max(0, Math.floor((levelId - 1) / CHAPTER_SIZE)));
  return CHAPTERS[index];
}

export function mapUrl(chapter: Chapter): string {
  return \`\${import.meta.env.BASE_URL}maps/chapter-\${chapter.n}-map.svg\`;
}

export function backgroundUrl(chapter: Chapter): string {
  return \`\${import.meta.env.BASE_URL}maps/chapter-\${chapter.n}-background.svg\`;
}
`,
);
console.log(`Imported ${entries.length} chapters into ${OUT} and src/game/chapters.ts`);
