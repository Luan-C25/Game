// Writes the template pack zip into the Worker as a base64 module.
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildPack } from "./pack.ts";

const out = join(import.meta.dirname, "..", "src/worker/generated");
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "pack.ts"), `// Generated by scripts/gen-pack.ts. Do not edit.\nexport const PACK_ZIP_BASE64 = "${Buffer.from(buildPack()).toString("base64")}";\n`);
