// Copies the depth-update art (pots, characters, streak badges, gift kiln)
// from design/depth/ into public/depth/, and writes src/game/characters.ts
// from design/depth/characters/characters.json.
// Re-run after the design changes:  node scripts/import-depth-art.mjs
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';

const SRC = 'design/depth/';
const OUT = 'public/depth/';
mkdirSync(OUT, { recursive: true });

let copied = 0;
const copy = (from, to = from.split('/').pop()) => {
  copyFileSync(SRC + from, OUT + to);
  copied++;
};

// Pots: fired, gold and empty for each chapter, plus the generic outline.
for (const f of readdirSync(SRC + 'pots')) {
  if (/^pot-.*\.svg$/.test(f)) copy(`pots/${f}`);
}

// Characters: a small map figure and a larger one for beside the board.
const characters = JSON.parse(readFileSync(SRC + 'characters/characters.json', 'utf8'));
for (const c of characters) {
  copy(`characters/${c.files.map}`, `char-${c.id}-map.svg`);
  copy(`characters/${c.files.side}`, `char-${c.id}-side.svg`);
}

// Streak badges, gift kiln and the Daily Kiln icon.
for (const f of readdirSync(SRC + 'streaks')) {
  if (/^(badge-(7|14|21|month-\d\d|locked)|gift-kiln-(closed|ready|open)|icon-daily-kiln)\.svg$/.test(f)) {
    copy(`streaks/${f}`);
  }
}
// The year badge carries sample text; the game writes its own label over a
// copy with the text taken out.
const year = readFileSync(SRC + 'streaks/badge-year-template.svg', 'utf8').replace(/<text\b[^>]*>[^<]*<\/text>/g, '');
writeFileSync(OUT + 'badge-year.svg', year);
copied++;

const gift = characters.filter((c) => c.kind === 'gift').sort((a, b) => a.giftOrder - b.giftOrder);
const shop = characters.filter((c) => c.kind === 'shop');
if (gift.length !== 6 || shop.length !== 6) throw new Error('expected six gift and six shop characters');
const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const entry = (c) =>
  `  { id: ${q(c.id)}, name: ${q(c.name)}, blurb: ${q(c.description)}, homeChapter: ${c.homeChapter}, price: ${c.kind === 'shop' ? c.price : 0} },`;

writeFileSync(
  'src/game/characters.ts',
  `/**
 * Collectable characters. Generated by scripts/import-depth-art.mjs from
 * design/depth/characters/characters.json; do not edit by hand. Saves store
 * the ids, so keep them stable once shipped.
 */

export interface Character {
  id: string;
  name: string;
  blurb: string;
  /** The chapter whose map they stand on. */
  homeChapter: number;
  /** Coins in the shop; 0 for gift characters, which are never sold. */
  price: number;
}

/** Given in this order on day 7 of the daily gift. Never random. */
export const GIFT_CHARACTERS: Character[] = [
${gift.map(entry).join('\n')}
];

/** Bought with coins in the shop. */
export const SHOP_CHARACTERS: Character[] = [
${shop.map(entry).join('\n')}
];

export const CHARACTERS: Character[] = [...GIFT_CHARACTERS, ...SHOP_CHARACTERS];

/** The next gift character not yet owned, or null when all are owned. */
export function nextGiftCharacter(owned: string[]): Character | null {
  return GIFT_CHARACTERS.find((c) => !owned.includes(c.id)) ?? null;
}

export function characterById(id: string): Character | undefined {
  return CHARACTERS.find((c) => c.id === id);
}

/** The small figure that stands on a chapter map. */
export function characterMapUrl(id: string): string {
  return \`\${import.meta.env.BASE_URL}depth/char-\${id}-map.svg\`;
}

/** The larger figure that keeps the player company beside the board. */
export function characterSideUrl(id: string): string {
  return \`\${import.meta.env.BASE_URL}depth/char-\${id}-side.svg\`;
}
`,
);
console.log(`Copied ${copied} files into ${OUT}; wrote src/game/characters.ts (${characters.length} characters)`);
