// Builds design/depth/overview.html and NOTES.md from each group's manifest.json and NOTES-part.md.
// Run: node design/depth/build-overview.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const groups = [
  ['pots', 'Pottery shelf: pots and shelf'],
  ['characters', 'Characters'],
  ['streaks', 'Streak badges, gift kiln, Daily Kiln'],
  ['finishes', 'Glazes, exit effects, shop'],
];
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;');

let html = `<!doctype html><html lang="en-AU"><head><meta charset="utf-8"><title>Glazeway depth art</title>
<meta name="viewport" content="width=device-width,initial-scale=1">
<style>
body{margin:0;padding:16px;background:#2b2f36;color:#f4ead8;font-family:'Baloo 2',system-ui,sans-serif}
h1{margin:0 0 4px}h2{margin:32px 0 8px;border-bottom:2px solid #555b66;padding-bottom:4px}
.grid{display:flex;flex-wrap:wrap;gap:12px;align-items:flex-end}
figure{margin:0;background:#e9dcc3;border-radius:10px;padding:8px;color:#4a3320;font-size:11px;text-align:center;max-width:420px}
figure img{display:block;margin:0 auto 4px;max-width:100%;height:auto}
.doc{background:#e9dcc3;color:#4a3320;border-radius:10px;padding:8px 12px;font-size:13px}
a{color:#7a3b12}
</style></head><body><h1>Glazeway depth update: art overview</h1>
<p>Generated by build-overview.mjs from each group's manifest.json. Scripts: build-pots, build-characters, build-streaks, build-finishes.</p>`;
let notes = `# Depth update art\n\nDesign only. Nothing in \`src/\` was changed. Open \`overview.html\` from disk to see everything.\nRegenerate: \`node design/depth/build-pots.mjs\`, \`build-characters.mjs\`, \`build-streaks.mjs\`, \`build-finishes.mjs\`, then \`node design/depth/build-overview.mjs\`.\n\nStyle: flat vector, as the chapter maps (ground shadow, darker underside, one highlight; no gradients, sparkles or textures). Okabe-Ito tile colours never change.\n\n`;
let count = 0;
for (const [dir, title] of groups) {
  const mp = path.join(here, dir, 'manifest.json');
  if (!fs.existsSync(mp)) { html += `<h2>${title}</h2><p>manifest missing</p>`; continue; }
  const items = JSON.parse(fs.readFileSync(mp, 'utf8'));
  html += `<h2>${title}</h2><div class="grid">`;
  notes += `## ${title}\n\n| File | Size |\n|---|---|\n`;
  for (const it of items) {
    count++;
    const rel = `${dir}/${it.file}`;
    notes += `| \`${rel}\` | ${it.width && it.height ? it.width + ' x ' + it.height : 'notes'} |\n`;
    if (it.file.endsWith('.svg')) html += `<figure><img src="${rel}" alt="${esc(it.label || it.file)}" loading="lazy"><div>${esc(it.label || it.file)}<br>${it.width} x ${it.height}</div></figure>`;
    else html += `<div class="doc"><a href="${rel}">${esc(it.label || it.file)}</a></div>`;
  }
  html += `</div>`;
  notes += `\n`;
  const np = path.join(here, dir, 'NOTES-part.md');
  if (fs.existsSync(np)) notes += fs.readFileSync(np, 'utf8').replace(/^#\s.*\n/, '').replace(/^#/gm, '###') + `\n\n`;
}
html += `</body></html>`;
fs.writeFileSync(path.join(here, 'overview.html'), html);
fs.writeFileSync(path.join(here, 'NOTES.md'), notes);
console.log('items', count);
